#!/usr/bin/env python3
"""patch_v3_6_0_comm_monitor_p7_types_agg.py

Generate an aggregate `statable_types.h` in by_layer mode.

Root cause:
  _generate_all_by_layer produces statable_types_common.h and per-layer
  statable_types_<Layer>.h but does NOT emit statable_types.h.
  comm_monitor's registry.c includes "statable_types.h" (matching flat mode)
  and therefore fails to compile in by_layer mode.

Fix:
  In _generate_all_by_layer, after common files are generated, emit an
  aggregator statable_types.h that includes common + per-layer headers
  and declares `extern SystemContext_t g_ctx;`.

Idempotent.
"""
import sys
from pathlib import Path

CODE = Path(__file__).resolve().parent.parent.parent
TARGET = CODE / "codegen" / "c_code_generator.py"


def main() -> int:
    print("=== patch_v3_6_0_comm_monitor_p7_types_agg ===")
    if not TARGET.is_file():
        print(f"[error] not found: {TARGET}", file=sys.stderr)
        return 1

    text = TARGET.read_text(encoding="utf-8")

    if "statable_types.h aggregate (by_layer mode)" in text:
        print(f"  [skip] already patched: {TARGET.name}")
        return 0

    old = (
        "            common_names = list(self.COMMON_FILES) + [\n"
        "                self.super_loop_filename\n"
        "            ]\n"
        "            for fname in common_names:\n"
        "                if (fname == 'statable_all.h'\n"
        "                        and not self.config.generate_super_include):\n"
        "                    continue\n"
        "                content = self._run_steps_multi(\n"
        "                    fname, layers, global_defs\n"
        "                )\n"
        "                generated_files[fname] = content\n"
        "            generated_files = self._merge_comm_monitor_files(generated_files, global_defs)\n"
        "            return generated_files"
    )
    new = (
        "            common_names = list(self.COMMON_FILES) + [\n"
        "                self.super_loop_filename\n"
        "            ]\n"
        "            for fname in common_names:\n"
        "                if (fname == 'statable_all.h'\n"
        "                        and not self.config.generate_super_include):\n"
        "                    continue\n"
        "                content = self._run_steps_multi(\n"
        "                    fname, layers, global_defs\n"
        "                )\n"
        "                generated_files[fname] = content\n"
        "            # statable_types.h aggregate (by_layer mode)\n"
        "            # Common modules such as comm_monitor include\n"
        "            # \"statable_types.h\" directly (flat-mode compatible name).\n"
        "            # Provide an aggregator unifying common + per-layer headers.\n"
        "            _agg = [\n"
        "                '/**',\n"
        "                ' * @file    statable_types.h',\n"
        "                ' * @brief   Aggregator of per-layer type headers',\n"
        "                ' *',\n"
        "                ' * @note    Code auto-generated by StaTable',\n"
        "                ' */',\n"
        "                '#pragma once',\n"
        "                '',\n"
        "                '#include \"statable_types_common.h\"',\n"
        "            ]\n"
        "            for _ln, _sm in layers:\n"
        "                if _ln:\n"
        "                    _agg.append(\n"
        "                        f'#include \"{_ln}/statable_types_{_ln}.h\"')\n"
        "            _agg.append('')\n"
        "            _agg.append('extern SystemContext_t g_ctx;')\n"
        "            _agg.append('')\n"
        "            generated_files['statable_types.h'] = '\\n'.join(_agg) + '\\n'\n"
        "            generated_files = self._merge_comm_monitor_files(generated_files, global_defs)\n"
        "            return generated_files"
    )

    if old not in text:
        print("[error] anchor not found in _generate_all_by_layer", file=sys.stderr)
        return 1

    text = text.replace(old, new, 1)
    TARGET.write_text(text, encoding="utf-8")
    print(f"  [patched] {TARGET.name}")
    print("=== done ===")
    return 0


if __name__ == "__main__":
    sys.exit(main())